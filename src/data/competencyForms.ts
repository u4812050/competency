export function calculateAssessmentScores(
  form: CompetencyFormTemplate,
  selfScores: Record<string, number>,
  supervisorScores: Record<string, number>,
  wardYears?: number
): {
  selfTotalScore: number;
  selfMaxScore: number;
  selfPercentage: number;
  selfAnsweredCount: number;
  supervisorTotalScore: number;
  supervisorMaxScore: number;
  supervisorPercentage: number;
  supervisorAnsweredCount: number;
  supervisorTier: CompetencyTier;
  sectionBreakdowns: SectionScoreBreakdown[];
} {
  let selfTotalScore = 0;
  let selfAnsweredCount = 0;
  let supervisorTotalScore = 0;
  let supervisorAnsweredCount = 0;
  let totalItems = 0;

  const activeSections = getApplicableSections(form, wardYears);
  const sectionBreakdowns: SectionScoreBreakdown[] = activeSections.map((section) => {
    let secSelf = 0;
    let secSelfCount = 0;
    let secSup = 0;
    let secSupCount = 0;
    const itemCount = section.items.length;
    const secMax = itemCount * 3;
    totalItems += itemCount;

    for (const item of section.items) {
      const sVal = selfScores[item.id];
      if (sVal === 1 || sVal === 2 || sVal === 3) {
        secSelf += sVal;
        secSelfCount += 1;
        selfTotalScore += sVal;
        selfAnsweredCount += 1;
      }
      const supVal = supervisorScores[item.id];
      if (supVal === 1 || supVal === 2 || supVal === 3) {
        secSup += supVal;
        secSupCount += 1;
        supervisorTotalScore += supVal;
        supervisorAnsweredCount += 1;
      }
    }

    return {
      sectionId: section.id,
      shortTitle: section.shortTitle,
      title: section.title,
      itemCount,
      maxScore: secMax,
      selfScore: secSelf,
      selfAnsweredCount: secSelfCount,
      selfPercentage: secMax > 0 ? Number(((secSelf * 100) / secMax).toFixed(2)) : 0,
      supervisorScore: secSup,
      supervisorAnsweredCount: secSupCount,
      supervisorPercentage: secMax > 0 ? Number(((secSup * 100) / secMax).toFixed(2)) : 0,
    };
  });

  const maxScore = totalItems * 3;
  const selfPercentage = maxScore > 0 ? Number(((selfTotalScore * 100) / maxScore).toFixed(2)) : 0;
  const supervisorPercentage =
    maxScore > 0 ? Number(((supervisorTotalScore * 100) / maxScore).toFixed(2)) : 0;

  return {
    selfTotalScore,
    selfMaxScore: maxScore,
    selfPercentage,
    selfAnsweredCount,
    supervisorTotalScore,
    supervisorMaxScore: maxScore,
    supervisorPercentage,
    supervisorAnsweredCount,
    supervisorTier: classifyCompetencyTier(supervisorPercentage, supervisorAnsweredCount > 0),
    sectionBreakdowns,
  };
}
