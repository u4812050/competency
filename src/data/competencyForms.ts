export function getFormById(formId: FormId): CompetencyFormTemplate {
  return COMPETENCY_FORMS.find((f) => f.id === formId) ?? COMPETENCY_FORMS[0];
}

export function getFormsByGroup(group: CompetencyGroup): CompetencyFormTemplate[] {
  return COMPETENCY_FORMS.filter((f) => f.group === group);
}

export function getGroupMeta(group: CompetencyGroup): CompetencyGroupMeta {
  return COMPETENCY_GROUPS.find((g) => g.id === group) ?? COMPETENCY_GROUPS[0];
}

export function isSectionApplicableForWardYears(
  section: CompetencySection,
  wardYears?: number
): boolean {
  if (!section.experienceRange || wardYears === undefined || !Number.isFinite(wardYears)) {
    return true;
  }
  const years = Math.max(0, wardYears);
  switch (section.experienceRange) {
    case '0-1 ปี':
      return years >= 0 && years < 1;
    case '1-3 ปี':
      return years >= 1 && years < 3;
    case '3-5 ปี':
      return years >= 3 && years < 5;
    case '5-10 ปี':
      return years >= 5 && years < 10;
    case '10 ปี ขึ้นไป':
      return years >= 10;
    default:
      return true;
  }
}

export function getApplicableSections(
  form: CompetencyFormTemplate,
  wardYears?: number
): CompetencySection[] {
  const hasExperienceLevels = form.sections.some((s) => Boolean(s.experienceRange));
  if (!hasExperienceLevels || wardYears === undefined || !Number.isFinite(wardYears)) {
    return form.sections;
  }
  const matched = form.sections.filter((s) => isSectionApplicableForWardYears(s, wardYears));
  return matched.length > 0 ? matched : [form.sections[0]];
}

export function getFormTotalItems(form: CompetencyFormTemplate, wardYears?: number): number {
  return getApplicableSections(form, wardYears).reduce((acc, s) => acc + s.items.length, 0);
}

export function classifyCompetencyTier(percentage: number, hasSupervisorScores: boolean): CompetencyTier {
  if (!hasSupervisorScores) return 'pending';
  if (percentage >= 86) return 'exceed';
  if (percentage >= 66) return 'meet';
  return 'need_improvement';
}

